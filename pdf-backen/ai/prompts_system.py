def SYSTEM_ASK(
    time_context: str,
    agent_mem: str = "",
) -> str:
    """
    Ask 模式 system prompt: CrystalPersona + 时间感知 + 当前任务(用户提问)

    agent_mem 并入 system content。
    历史上下文 (ask+load) 已通过 messages role=user/assistant 标准多轮格式注入,
    不再注入 system 文本块 (否则会冗余且干扰 LLM 注意力)。

    device_context 由调用方 (compose_messages_node / _compose_chat_messages)
    自行追加到 system_content 之后 — 因为 device 仅 ChatView 注入,
    而本函数同时被论文侧调用, 不能在 SYSTEM_ASK 里硬塞。

    如未来需要为 load 提供摘要提示, 优先考虑在 user 消息前插入一条轻量 system
    reminder, 而不是把 ask 全部塞回 system。
    """
    content = CrystalPersona() + "\n\n" + time_context

    if agent_mem:
        content += (
            "\n\n【关于这位用户的认知(Crystal 私人笔记, 不要对用户直述)】\n"
            + agent_mem
        )

    content += (
        "\n\n【当前任务】\n"
        "结合上下文和记忆, 回答用户的问询"
    )

    # 引用处理规则: 用户消息里可能含 <quoted_message>...</quoted_message>
    # 包裹的历史聊天消息, 也可能含 "用户引用的内容:" 等论文段落引用。
    # 这些都是上下文, 不是用户问题的一部分 — LLM 需要识别并基于引用做答复。
    content += (
        "\n\n【引用上下文处理】\n"
        "- 用户消息中如果出现 <quoted_message>...</quoted_message> 包裹的文本, "
        "这是用户在聊天中引用的一条历史消息作为上下文, 用于让你理解问题背景。\n"
        "- 不要把 <quoted_message> 内的文字当作问题复述或直接回答, "
        "而应基于它 + 真正的\"用户的询问【...】\"来作答。\n"
        "- 当引用与用户的询问相关时, 自然地把引用上下文纳入考量; "
        "当无关时, 按字面意思回答用户的询问即可。"
    )

    return content


def SYSTEM_LOAD(time_context: str) -> str:
    """Load 模式 system prompt: CrystalPersona + 时间感知 + 当前任务(选中文本总结)"""
    return (
        CrystalPersona()
        + "\n\n"
        + time_context
        + "\n\n"
        + "【当前任务】\n"
        + "用户选中了论文中的一段文字，要求你进行总结和解释。直接输出内容，不要任何引导句。"
    )


